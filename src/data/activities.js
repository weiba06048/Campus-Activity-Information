export const CATEGORY_BY_ID = Object.fromEntries(CATEGORIES.map((item) => [item.id, item]));
export const ACTIVITY_BY_ID = Object.fromEntries(ACTIVITIES.map((item) => [item.id, item]));

// 长期开放的活动排在最后
function sortKey(activity) {
  return activity.startDate || "9999-12-31";
}

// activities 参数让调用方可以把「用户自己发布的活动」一起传进来
export function activitiesOfCategory(categoryId, activities = ACTIVITIES) {
  return activities.filter((item) => item.categoryId === categoryId).sort((a, b) =>
    sortKey(a).localeCompare(sortKey(b)),
  );
}

export function categoryOf(activity) {
  return CATEGORY_BY_ID[activity.categoryId];
}

// 站内搜索：命中标题、标签、板块名、主办方、地点与简介
export function searchActivities(keyword, activities = ACTIVITIES) {
  const query = String(keyword || "").trim().toLowerCase();
  if (!query) return [];
  return activities.map((activity) => {
    const category = categoryOf(activity);
    const haystacks = [
      { text: activity.title, weight: 6 },
      { text: activity.tags.join(" "), weight: 4 },
      { text: category?.name || "", weight: 3 },
      { text: activity.organizer, weight: 2 },
      { text: activity.location, weight: 2 },
      { text: activity.summary, weight: 1 },
    ];
    let score = 0;
    for (const item of haystacks) {
      if (item.text.toLowerCase().includes(query)) score += item.weight;
    }
    return { activity, score };
  })
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score || sortKey(a.activity).localeCompare(sortKey(b.activity)))
    .map((item) => item.activity);
}
